            <p>Mirror Dungeon adalah mode permainan mingguan di mana Anda membangun tim dan koleksi E.G.O Gift secara bertahap untuk melewati beberapa lantai dan mengalahkan bos di akhir. Ini adalah sumber utama untuk mendapatkan <strong><i>Egoshards</i></strong> dan <strong><i>EXP Battle Pass</i></strong> setiap minggunya.</p>
            <p>Pemain dapat memilih tingkat kesulitan Normal atau Hard, dengan hadiah yang lebih besar di tingkat Hard.</p>
