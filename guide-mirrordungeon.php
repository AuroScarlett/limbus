        <section class="guide-section">
            <h2><i class="fas fa-project-diagram"></i> Alur Permainan: Dari Awal Hingga Akhir</h2>
            <p>Setiap "run" di Mirror Dungeon mengikuti alur yang sama:</p>
            <ol class="steps-list">
                <li><strong>Pemilihan Awal:</strong> Anda memilih beberapa Sinner awal (Identitas dan E.G.O) untuk memulai petualangan. Jika anda memilih mode normal maka semua level karakter anda akan diubah menjadi 50.</li>
                <li><strong>Navigasi Peta:</strong> Anda akan disajikan peta dengan berbagai "node" (titik). Anda memilih jalur mana yang akan diambil.</li>
                <li><strong>Menyelesaikan Node:</strong> Setiap node memiliki tipe yang berbeda, seperti pertarungan, event acak, atau toko.</li>
                <li><strong>Mengalahkan Bos Lantai:</strong> Di akhir setiap lantai, Anda akan menghadapi bos yang kuat. Mengalahkannya akan memberi Anda hadiah E.G.O Gift yang bagus dan kesempatan untuk beristirahat.</li>
                <li><strong>Mengulang:</strong> Proses ini diulang untuk beberapa lantai hingga Anda mencapai dan mengalahkan bos terakhir.</li>
            </ol>
            </section>

        <section class="guide-section">
            <h2><i class="fas fa-gift"></i> Konsep Kunci: E.G.O Gift</h2>
            <p>E.G.O Gift adalah kunci kesuksesan di Mirror Dungeon. Ini adalah item pasif yang Anda kumpulkan setelah pertarungan atau dari event. Gift ini memberikan berbagai macam bonus, mulai dari menaikkan damage tipe tertentu, menambah status efek, hingga memberikan buff unik.</p>
            <blockquote style="margin-top: 15px; border-left-color: var(--accent-color);">
                <strong>Strategi Inti:</strong> Build Anda ditentukan oleh E.G.O Gift yang Anda dapatkan. Jika Anda mendapatkan banyak Gift yang memperkuat Bleed, maka fokuslah menggunakan Identitas Bleed untuk memaksimalkan sinergi.
            </blockquote>
        </section>
        
        <section class="guide-section">
            <h2><i class="fas fa-chess-knight"></i> Strategi Kunci untuk Kesuksesan</h2>
            
            <h3 style="margin-top:20px;">1. Pilih Tim Awal yang Bersinergi</h3>
            <p>Meskipun Anda bisa merekrut Sinner lain di tengah jalan, 3-6 Sinner pertama Anda sangat menentukan. Mulailah dengan tim inti yang sudah memiliki sinergi, misalnya 5 karakter Bleed + 1 karakter Poise.</p>

            <h3 style="margin-top:20px;">2. Fokus pada Satu Tema E.G.O Gift</h3>
            <p>Jangan mengambil Gift secara acak. Tentukan satu atau dua tema dan fokuslah padanya. Contoh tema yang kuat:</p>
            <ul>
                <li><strong>Tema Bleed:</strong> Cari Gift seperti "Wound Clerid" dan "Ruptured Blood Sac".</li>
                <li><strong>Tema Charge:</strong> Cari Gift seperti "Miniature Telepole" dan "Patrolling Flashlight".</li>
                <li><strong>Tema Poise:</strong> Cari Gift "Nebulizer" dan "Clear Mirror, Calm Water".</li>
            </ul>

            <h3 style="margin-top:20px;">3. Prioritaskan Jalur di Peta</h3>
            <p>Di awal, prioritaskan node yang melawan abnormality seperti Focused Encounter<img alt="Peccatulum Fight" src="assets/gambar/icon/MonsterEncounterIcon.png" width="30px" height="30px" align="center"> melawan Peccatulum, Abnormality Event<img alt="Event" src="assets/gambar/icon/EventEncounterIcon.png" width="30px" height="30px" align="center"> dan Abnormality Focused Encounter<img alt="ToadCoreIcon" src="assets/gambar/icon/BlubberingToadCoreIcon.png" width="30px" height="30px" align="center"> (terutama yang Sulit/Elite jika tim Anda kuat) untuk mengumpulkan Cost (mata uang dungeon) dan E.G.O Gift sebanyak mungkin. Saat mengunjungi Toko (Rest Stop) cari dan upgrade E.G.O Gift yang diperlukan saat sudah memiliki cukup Starlight, jangan lupa juga untuk menggabungkan E.G.O gift tertentu agar menjadi E.G.O Gift yang lebih bagus dan kuat.</p>
        </section>

